// 路由 → 页面的总分发（iOS AppShell.swift:459-601）。穷举 when，不写 else。
package com.geek.umbra.navigation

import androidx.compose.runtime.Composable

@Composable
fun RouteScreen(r: Route) {
    when (r) {
        Route.ChatContacts -> com.geek.umbra.feature.chat.ChatContactsScreen()
        is Route.ChatThread -> com.geek.umbra.feature.chat.ChatThreadScreen(r.conv)
        Route.RemList -> com.geek.umbra.feature.reminder.RemListScreen()
        is Route.RemDetail -> com.geek.umbra.feature.reminder.RemDetailScreen(r.id)
        is Route.RemEdit -> com.geek.umbra.feature.reminder.RemEditScreen(r.id, r.prefill)
        Route.ToolHome -> com.geek.umbra.feature.tool.ToolHomeScreen()
        Route.ToolWidgets -> com.geek.umbra.feature.tool.ToolWidgetsScreen()
        Route.TaskList -> com.geek.umbra.feature.task.TaskListScreen()
        is Route.TaskDetail -> com.geek.umbra.feature.task.TaskDetailScreen(r.id)
        Route.InspList -> com.geek.umbra.feature.inspiration.InspListScreen()
        is Route.InspDetail -> com.geek.umbra.feature.inspiration.InspDetailScreen(r.id)
        is Route.InspEdit -> com.geek.umbra.feature.inspiration.InspEditScreen(r.id)
        Route.MoneyHome -> com.geek.umbra.feature.money.MoneyHomeScreen()
        Route.MoneyList -> com.geek.umbra.feature.money.MoneyListScreen()
        is Route.MoneyAdd -> com.geek.umbra.feature.money.MoneyAddScreen(r.id, r.focusAccount)
        Route.MoneyCats -> com.geek.umbra.feature.money.MoneyCatsScreen()
        is Route.MoneyCat -> com.geek.umbra.feature.money.MoneyCatScreen(r.slug)
        Route.MoneySettings -> com.geek.umbra.feature.money.MoneySettingsScreen()
        Route.MoneyRecur -> com.geek.umbra.feature.money.MoneyRecurScreen()
        is Route.MoneyRecurEdit -> com.geek.umbra.feature.money.MoneyRecurEditScreen(r.id)
        Route.MeHome -> com.geek.umbra.feature.me.MeHomeScreen()
        Route.MePhrases -> com.geek.umbra.feature.phrases.PhrasesScreen()
        is Route.MePhraseEdit -> com.geek.umbra.feature.phrases.PhraseEditScreen(r.id)
        Route.MeDevices -> com.geek.umbra.feature.me.DevicesScreen()
        is Route.DeviceDetail -> com.geek.umbra.feature.me.DeviceDetailScreen(r.id)
        Route.MeCaps -> com.geek.umbra.feature.me.CapsScreen()
        Route.MeMemory -> com.geek.umbra.feature.memory.MemoryScreen()
        is Route.MeMemoryItem -> com.geek.umbra.feature.memory.MemoryItemScreen(r.id)
        is Route.MeMemoryEdit -> com.geek.umbra.feature.memory.MemoryEditScreen(r.id, r.kind)
        Route.KbList -> com.geek.umbra.feature.knowledge.KbListScreen()
        is Route.KbDocs -> com.geek.umbra.feature.knowledge.KbDocsScreen(r.id, r.name)
        Route.MeDuty -> com.geek.umbra.feature.duty.DutyScreen()
        is Route.MeDutyEdit -> com.geek.umbra.feature.duty.DutyEditScreen(r.id)
        Route.MeDutyLog -> com.geek.umbra.feature.duty.DutyLogScreen()
        is Route.MeDutyFlow -> com.geek.umbra.feature.duty.DutyFlowScreen(r.id)
        is Route.MeDutyFlowRun -> com.geek.umbra.feature.duty.DutyFlowRunScreen(r.id)
        Route.MeDutyFlows -> com.geek.umbra.feature.duty.DutyFlowsScreen()
        Route.MeDutyFollows -> com.geek.umbra.feature.duty.DutyFollowsScreen()
        Route.MeDutyRules -> com.geek.umbra.feature.duty.DutyRulesScreen()
        Route.SetAccount -> com.geek.umbra.feature.account.AccountScreen()
        Route.SetShop -> com.geek.umbra.feature.account.ShopScreen()
        is Route.SetShopTheme -> com.geek.umbra.feature.theme.ShopThemeScreen(r.id)
        Route.SetShopHistory -> com.geek.umbra.feature.account.ShopHistoryScreen()
        Route.SetStorage -> com.geek.umbra.feature.account.StorageScreen()
        Route.SetPassword -> com.geek.umbra.feature.account.PasswordScreen()
        Route.SetSessions -> com.geek.umbra.feature.account.SessionsScreen()
        Route.SetDeactivate -> com.geek.umbra.feature.account.DeactivateScreen()
        Route.SetConn -> com.geek.umbra.feature.me.ConnScreen()
        Route.SetNotify -> com.geek.umbra.feature.me.NotifyScreen()
        Route.SetGeneral -> com.geek.umbra.feature.me.GeneralScreen()
        Route.SetAppearance -> com.geek.umbra.feature.theme.AppearanceScreen()
        Route.SetAbout -> com.geek.umbra.feature.me.AboutScreen()
        Route.VaultHome -> com.geek.umbra.feature.vault.VaultHomeScreen()
        Route.VaultCreate -> com.geek.umbra.feature.vault.VaultCreateScreen()
        Route.VaultKey -> com.geek.umbra.feature.vault.VaultKeyScreen()
        Route.VaultRecover -> com.geek.umbra.feature.vault.VaultRecoverScreen()
        is Route.VaultRecord -> com.geek.umbra.feature.vault.VaultRecordScreen(r.id, r.find)
        is Route.VaultEdit -> com.geek.umbra.feature.vault.VaultEditScreen(r.id)
        Route.VaultGen -> com.geek.umbra.feature.vault.VaultGenScreen()
        Route.VaultCheck -> com.geek.umbra.feature.vault.VaultCheckScreen()
        Route.VaultGroups -> com.geek.umbra.feature.vault.VaultGroupsScreen()
        Route.VaultProfiles -> com.geek.umbra.feature.vault.VaultProfilesScreen()
        Route.VaultTrash -> com.geek.umbra.feature.vault.VaultTrashScreen()
        Route.VaultImport -> com.geek.umbra.feature.vault.VaultImportScreen()
        Route.VaultSettings -> com.geek.umbra.feature.vault.VaultSettingsScreen()
        Route.VaultPwd -> com.geek.umbra.feature.vault.VaultPwdScreen()
        Route.VaultAutofill -> com.geek.umbra.feature.vault.VaultAutofillScreen()
    }
}
