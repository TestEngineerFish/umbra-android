/**
 * 页面用的文案出口（iOS `dutyTr`）：key + 字符串参数 → 当前语言的一句话。
 * 资源里的格式符都是 `%s` / `%1$s`（gen_strings 把 `%@` 转过来的），参数一律按字符串传。
 */
internal fun dutyTr(ctx: Context): DutyTr = { key, args ->
    val id = dutyStringRes(key)
    if (id == null) key else if (args.isEmpty()) ctx.getString(id) else ctx.getString(id, *args.toTypedArray())
}

/** 非 Composable 场景（Store 里拼「为什么」）用应用上下文。 */
internal val dutyAppTr: DutyTr get() = dutyTr(AppGraph.context)

/** Composable 里取文案出口：跟着 LocalContext（语言切换后整棵树重建，这里随之换新）。 */
@Composable
internal fun rememberDutyTr(): DutyTr {
    val ctx = LocalContext.current
    val conf = LocalConfiguration.current
    return remember(ctx, conf) { dutyTr(ctx) }
}

/** 按 key 取一句（无参数）。 */
@Composable
internal fun dutyL(key: String, vararg args: String): String = rememberDutyTr()(key, args.toList())
