/** 拖拽排序的纯计算（批次 020 §三）—— 整条排序链上唯一会算错的一步。iOS: MoneySync.swift:216 */
object MoneyCatOrder {
    /**
     * 把「一个方向的新顺序」贴回全量分类列表：只动这个方向占的那些位置，另一个方向的行原地不动
     * （两个方向的块谁在前是服务端 ORDER BY direction, seq 的事）。
     * 没被 slugs 提到的分类按原顺序垫在后面（与服务端 reorder_categories 同口径：端上清单可能是旧的）。
     */
    fun apply(cats: List<MoneyCatDTO>, direction: String, slugs: List<String>): List<MoneyCatDTO> {
        val inDir = cats.filter { it.direction == direction }
        val seen = HashSet<String>()
        val ordered = mutableListOf<MoneyCatDTO>()
        for (s in slugs) {
            if (s in seen) continue
            val c = inDir.firstOrNull { it.slug == s } ?: continue
            ordered.add(c)
            seen.add(s)
        }
        ordered += inDir.filter { it.slug !in seen }
        var i = 0
        return cats.map { c -> if (c.direction != direction) c else ordered[i++] }
    }

    /**
     * 拖完之后的 slug 清单。⚠️ 与 iOS 的差别：SwiftUI onMove 给的是 IndexSet + 「移除之前」的落点，
     * 靠 move(fromOffsets:toOffset:) 消化那一格偏差；Android 拖动给的是「移走前下标 from」和
     * 「最终落点下标 to」，所以这里按 removeAt(from) 再 add(to) 的语义算 —— 不要再套一次 iOS 的「往下减一」。
     * 下标越界时原样返回（拖动回调与列表刷新错拍时不该崩）。
     */
    fun moved(slugs: List<String>, from: Int, to: Int): List<String> {
        if (from !in slugs.indices) return slugs
        val next = slugs.toMutableList()
        val x = next.removeAt(from)
        next.add(to.coerceIn(0, next.size), x)
        return next
