/** 金额与月份展示。全项目金额展示只走这一个口。iOS: MoneySync.swift:56 */
object MoneyFmt {
    /**
     * 整数分 → "¥1,800.00"。固定 zh_CN 口径：千分位逗号、两位小数，不跟手机地区走。
     * 负数照 iOS 实际输出写成 "¥-38.00"（iOS 是 "¥" + NumberFormatter(zh_CN).string，后者对负数出 "-38.00"）。
     * 用整数算，不经 Double：分是精确值，没有理由绕一道浮点。
     */
    fun yuan(cents: Long): String {
        val neg = cents < 0
        val v = Math.abs(cents)
        val intPart = (v / 100).toString().reversed().chunked(3).joinToString(",").reversed()
        return "¥" + (if (neg) "-" else "") + intPart + "." + String.format(Locale.ROOT, "%02d", v % 100)
    }

    /** 带方向符号："-¥38.00" / "+¥320.00"。 */
    fun signed(cents: Long, income: Boolean): String = (if (income) "+" else "-") + yuan(cents)

    /**
     * 本地时区的 YYYY-MM。⚠️ 走 MoneyWireDate.ym，不拿手机的历法取年份：
     * 这个值是发给服务端的 ym，佛历手机上「本月」会变成 2569-10。iOS: MoneySync.swift:79
     */
    fun ymNow(): String = MoneyWireDate.ym(System.currentTimeMillis())

    /** "2026-08" → "2026 年 8 月"。 */
    fun ymLabel(ym: String): String {
        val y = ym.take(4)
        val m = ym.takeLast(2).toIntOrNull() ?: 0
        return "$y 年 $m 月"
    }

    /**
     * "2026-08" 挪 n 个月 → "2026-09"。跨年靠取模，不靠字符串拼；和 PC moneyKit.shiftYm 同口径。
     * iOS 用截断除法（t / 12、t % 12），t ≥ 0（公元年）时与 floorDiv / floorMod 一致；这里取后者，负数也不出怪月份。
     */
    fun shiftYm(ym: String, n: Int): String {
        val y = ym.take(4).toIntOrNull() ?: 2026
        val m = ym.takeLast(2).toIntOrNull() ?: 1
        val t = y * 12 + (m - 1) + n
        return String.format(Locale.ROOT, "%04d-%02d", Math.floorDiv(t, 12), Math.floorMod(t, 12) + 1)
    }

    /** 客户端时区当前偏移分钟（东八区 = +480），写 tz_offset_min 用。每次现取：时区 / 夏令时会变。 */
    val tzOffsetMin: Int get() = TimeZone.getDefault().getOffset(System.currentTimeMillis()) / 60_000
}

